def _resolve_telemac_variables(requested, var_index, is_3d):
    """
    Map requested variable names to columns of the SLF variable table.

    Returns a list of (requested_name, component_indices) where the value is
    the plain variable column for single indices, or the vector magnitude for
    multiple indices.
    """
    resolved = []

    for name in requested:
        key = " ".join(str(name).split()).upper()
        key = TELEMAC_ALIASES.get(key, key)

        if key in var_index:
            resolved.append((name, [var_index[key]]))
            continue

        if key in ("VELOCITY", "3D VELOCITY MAGNITUDE", "SCALAR VELOCITY"):
            if not is_3d and "SCALAR VELOCITY" in var_index:
                resolved.append((name, [var_index["SCALAR VELOCITY"]]))
                continue

            components = ["VELOCITY U", "VELOCITY V"]
            if is_3d and "VELOCITY W" in var_index:
                components.append("VELOCITY W")

            missing = [c for c in components if c not in var_index]
            if missing:
                raise ValueError(
                    f"Cannot resolve '{name}': the file provides neither "
                    f"SCALAR VELOCITY nor the components {missing}. "
                    f"Available variables: {sorted(var_index)}"
                )

            resolved.append((name, [var_index[c] for c in components]))
            continue

        raise ValueError(
            f"Variable '{name}' not found in the SELAFIN file. "
            f"Available variables: {sorted(var_index)}"
        )

    return resolved


def _evaluate_variables(resolved_variables, values):
    """Evaluate resolved variables on one row of SLF values."""
    out = {}
    for name, indices in resolved_variables:
        if len(indices) == 1:
            out[name] = float(values[indices[0]])
        else:
            out[name] = float(np.sqrt(np.sum(values[indices] ** 2)))
    return out


def _extract_telemac(result_file, variables, x_pts, y_pts, z_pts,
                     time, time_index, n_last, method, k):
    if not os.path.isfile(result_file):
        raise FileNotFoundError(f"SELAFIN file not found: {result_file}")

    slf = ppSELAFIN(result_file)
    slf.readHeader()
    slf.readTimes()

    var_names = [" ".join(v.split()) for v in slf.getVarNames()]
    var_index = {v.upper(): i for i, v in enumerate(var_names)}
    n_var = len(var_names)

    _, npoin, _, _, _, mesh_x, mesh_y = slf.getMesh()
    nplan = max(slf.getNPLAN(), 1)
    is_3d = nplan > 1
    n2d = npoin // nplan

    resolved_variables = _resolve_telemac_variables(variables, var_index, is_3d)

    if is_3d and "ELEVATION Z" not in var_index:
        raise ValueError(
            "The 3D SELAFIN file does not provide 'ELEVATION Z', which is "
            "required to locate the vertical planes. "
            f"Available variables: {sorted(var_index)}"
        )

    tree = spatial.cKDTree(np.column_stack((mesh_x[:n2d], mesh_y[:n2d])))
    k_use = 1 if method == "nearest" else min(k, n2d)

    records = []

    for i in range(x_pts.size):
        target_xy = (x_pts[i], y_pts[i])

        _, idx = tree.query(target_xy, k=k_use)
        idx_base = np.atleast_1d(idx)
        node_xy = np.column_stack((mesh_x[idx_base], mesh_y[idx_base]))
        weights = _idw_weights(node_xy, target_xy) if k_use > 1 else np.array([1.0])

        # Time-reduced values of all variables on all planes above the
        # selected horizontal nodes: shape (nplan, k_use, n_var).
        node_values = np.zeros((nplan, k_use, n_var))
        for p in range(nplan):
            for j, base in enumerate(idx_base):
                slf.readVariablesAtNode(int(base + p * n2d))
                node_values[p, j, :] = _reduce_time(
                    slf.getVarValuesAtNode(), time, time_index, n_last
                )

        # IDW across the k nodes on every plane: shape (nplan, n_var).
        plane_values = np.einsum("j,pjv->pv", weights, node_values)

        base_record = {"point": i, "x": x_pts[i], "y": y_pts[i]}

        if not is_3d:
            records.append(
                {**base_record, **_evaluate_variables(resolved_variables,
                                                      plane_values[0])}
            )
            continue

        z_profile = plane_values[:, var_index["ELEVATION Z"]]
        bed_z = z_profile[0]

        if z_pts is not None:
            # Select the plane closest to the requested height above the bed
            # (same convention as TelemacModel.extract_data_point).
            p = int(np.argmin(np.abs(z_profile - (bed_z + z_pts[i]))))
            records.append({
                **base_record,
                "z": z_pts[i],
                "plane": p + 1,
                "z_plane": z_profile[p],
                "z_above_bed": z_profile[p] - bed_z,
                **_evaluate_variables(resolved_variables, plane_values[p]),
            })
        else:
            # Full vertical profile: one row per plane.
            for p in range(nplan):
                records.append({
                    **base_record,
                    "plane": p + 1,
                    "z_plane": z_profile[p],
                    "z_above_bed": z_profile[p] - bed_z,
                    **_evaluate_variables(resolved_variables, plane_values[p]),
                })

    return pd.DataFrame(records)


