"""
Standalone extraction of 2D and 3D simulation results at user points.

This module exposes the depth-explicit extraction that drives the calibration
workflow (``TelemacModel.extract_data_point``) as a plain function that works
on any TELEMAC SELAFIN file (2D or 3D) or OpenFOAM VTK output without a model
instance, configuration file, or results-folder conventions::

    import hydroBayesCal as hbc
    df = hbc.extract_results("r3d_case.slf", variable="velocity",
                             x=[5.0, 7.5], y=[2.0, 2.5], z=0.05)

For 3D TELEMAC results the vertical plane closest to the requested height
above the local bed is selected via ``ELEVATION Z`` (same convention as the
calibration workflow). With ``z=None`` the full vertical profile is returned.
2D results and the 2D files generated by TELEMAC-3D are handled by the same
function. OpenFOAM VTK output (``foamToVTK``) is inherently 3D and sampled at
the exact (x, y, z) locations.
"""

import glob
import os

import numpy as np
import pandas as pd
from scipy import spatial

from hydroBayesCal.telemac.pputils.ppmodules.selafin_io_pp import ppSELAFIN

#: File endings treated as TELEMAC SELAFIN files.
SELAFIN_EXTENSIONS = (".slf", ".sel", ".srf", ".res")

#: File endings treated as OpenFOAM/VTK files.
VTK_EXTENSIONS = (".vtu", ".vtk", ".vtm", ".vtp")

#: Convenience aliases resolved against the variables present in the file.
TELEMAC_ALIASES = {
    "DEPTH": "WATER DEPTH",
    "WSE": "FREE SURFACE",
    "WATER SURFACE": "FREE SURFACE",
    "BED": "BOTTOM",
}


def extract_results(
        result_file,
        variable,
        x,
        y,
        z=None,
        time="last",
        time_index=0,
        n_last=5,
        method="idw",
        k=3,
):
    """
    Extract simulation results at one or more points from a TELEMAC SELAFIN
    (2D or 3D) file or from OpenFOAM VTK output.

    Parameters
    ----------
    result_file : str
        Path to a TELEMAC result file (``.slf``/``.sel``/``.srf``/``.res``),
        an OpenFOAM VTK file (``.vtu``/``.vtk``), or an OpenFOAM case
        directory containing a ``VTK/`` folder written by ``foamToVTK``.
    variable : str or list of str
        Variable name(s) to extract. TELEMAC SELAFIN variable names are
        matched case-insensitively (e.g. ``"WATER DEPTH"``); OpenFOAM field
        names as written by ``foamToVTK`` (e.g. ``"U"``, ``"k"``).
        The alias ``"velocity"`` resolves to the flow velocity magnitude in
        any file type (``SCALAR VELOCITY`` or ``sqrt(U^2+V^2)`` in 2D,
        ``sqrt(U^2+V^2+W^2)`` in 3D, ``|U|`` for OpenFOAM), and
        ``"velocity u"``, ``"velocity v"``, ``"velocity w"`` resolve to the
        individual components.
    x, y : float or array-like
        Horizontal coordinates of the extraction point(s).
    z : float or array-like, optional
        Vertical position of the extraction point(s) as height above the
        local bed (TELEMAC 3D) or absolute z-coordinate (OpenFOAM).
        For a 3D TELEMAC file, the vertical plane whose elevation is closest
        to ``bed elevation + z`` is selected per point. If ``z=None``, a 3D
        TELEMAC file yields the full vertical profile (one row per plane),
        and a 2D file is extracted as usual (``z`` is ignored in 2D).
    time : {"last", "index", "mean_last"}, optional
        Temporal reduction: final time step (default), the time step given by
        ``time_index``, or the mean of the last ``n_last`` time steps. For an
        OpenFOAM case directory the modes select/average the VTK time
        directories analogously; a single VTK file has exactly one time step.
    time_index : int, optional
        Time-step index used with ``time="index"``. Default: 0.
    n_last : int, optional
        Number of final time steps averaged with ``time="mean_last"``.
        Default: 5.
    method : {"idw", "nearest"}, optional
        Spatial sampling: inverse-distance-weighted interpolation over the
        ``k`` nearest mesh nodes (default) or the nearest node only.
        ``"interpolated"`` is accepted as an alias of ``"idw"``.
    k : int, optional
        Number of nearest nodes for IDW interpolation. Default: 3.

    Returns
    -------
    pandas.DataFrame
        One row per extraction point (or per point and vertical plane when a
        3D TELEMAC file is queried with ``z=None``) with columns ``point``,
        ``x``, ``y``, the vertical position columns where applicable
        (``plane``, ``z_plane``, ``z_above_bed``), and one column per
        requested variable.
    """
    variables = [variable] if isinstance(variable, str) else list(variable)

    x_pts = np.atleast_1d(np.asarray(x, dtype=float))
    y_pts = np.atleast_1d(np.asarray(y, dtype=float))
    if x_pts.shape != y_pts.shape:
        raise ValueError(
            f"x and y must have the same length, got {x_pts.size} and {y_pts.size}."
        )

    if z is not None:
        z_pts = np.broadcast_to(
            np.atleast_1d(np.asarray(z, dtype=float)), x_pts.shape
        ).copy()
    else:
        z_pts = None

    if method == "interpolated":
        method = "idw"
    if method not in ("idw", "nearest"):
        raise ValueError("method must be 'idw' or 'nearest'.")

    if time not in ("last", "index", "mean_last"):
        raise ValueError("time must be 'last', 'index', or 'mean_last'.")

    ext = os.path.splitext(result_file)[1].lower()

    if os.path.isdir(result_file) or ext in VTK_EXTENSIONS:
        return _extract_openfoam(
            result_file, variables, x_pts, y_pts, z_pts,
            time, time_index, n_last, method, k
        )

    if ext in SELAFIN_EXTENSIONS:
        return _extract_telemac(
            result_file, variables, x_pts, y_pts, z_pts,
            time, time_index, n_last, method, k
        )

    raise ValueError(
        f"Unrecognized result file type '{ext}'. Expected a TELEMAC SELAFIN "
        f"file {SELAFIN_EXTENSIONS}, an OpenFOAM VTK file {VTK_EXTENSIONS}, "
        "or an OpenFOAM case directory."
    )


def _reduce_time(all_times_values, time, time_index, n_last):
    """Reduce a (n_times, ...) array to one time step according to the mode."""
    all_times_values = np.asarray(all_times_values, dtype=float)

    if time == "last":
        return all_times_values[-1]
    if time == "index":
        return all_times_values[time_index]
    return np.mean(all_times_values[-n_last:], axis=0)


def _idw_weights(node_xy, target_xy):
    """Inverse-distance weights of nodes at node_xy relative to target_xy."""
    distances = np.linalg.norm(
        np.asarray(node_xy, dtype=float) - np.asarray(target_xy, dtype=float),
        axis=1
    )
    distances[distances == 0] = np.finfo(float).eps
    weights = 1.0 / distances
    return weights / weights.sum()


