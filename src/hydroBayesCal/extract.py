def _collect_vtk_files(source):
    """Return the time-sorted VTK files of an OpenFOAM case directory."""
    vtk_dir = os.path.join(source, "VTK")
    search_root = vtk_dir if os.path.isdir(vtk_dir) else source

    def step_index(path):
        suffix = os.path.basename(os.path.dirname(path)).rsplit("_", 1)[-1]
        return int(suffix) if suffix.isdigit() else 0

    vtk_files = sorted(
        glob.glob(os.path.join(search_root, "**", "internal.vtu"), recursive=True),
        key=step_index
    )

    if not vtk_files:
        raise FileNotFoundError(
            f"No internal.vtu files found under: {search_root}. "
            "Run foamToVTK first or pass a .vtu/.vtk file directly."
        )

    return vtk_files


def _resolve_openfoam_variables(requested, point_data_keys):
    """
    Map requested variable names to OpenFOAM point-data fields.

    Returns a list of (requested_name, field_name, component) with
    component = None for scalars or vector magnitudes, or 0/1/2 for a
    vector component.
    """
    lower_map = {key.lower(): key for key in point_data_keys}

    component_aliases = {
        "velocity u": 0, "u_x": 0, "ux": 0,
        "velocity v": 1, "u_y": 1, "uy": 1,
        "velocity w": 2, "u_z": 2, "uz": 2,
    }

    resolved = []

    for name in requested:
        key = str(name).strip().lower()

        if key == "velocity":
            if "u" not in lower_map:
                raise ValueError(
                    "Cannot resolve 'velocity': field 'U' not found. "
                    f"Available fields: {sorted(point_data_keys)}"
                )
            resolved.append((name, lower_map["u"], None))
        elif key in component_aliases:
            if "u" not in lower_map:
                raise ValueError(
                    f"Cannot resolve '{name}': field 'U' not found. "
                    f"Available fields: {sorted(point_data_keys)}"
                )
            resolved.append((name, lower_map["u"], component_aliases[key]))
        elif key in lower_map:
            resolved.append((name, lower_map[key], None))
        else:
            raise ValueError(
                f"Field '{name}' not found in the VTK output. "
                f"Available fields: {sorted(point_data_keys)}"
            )

    return resolved


def _extract_openfoam(source, variables, x_pts, y_pts, z_pts,
                      time, time_index, n_last, method, k):
    import pyvista as pv

    if z_pts is None:
        raise ValueError(
            "OpenFOAM results are three-dimensional: provide the z "
            "coordinate(s) of the extraction point(s)."
        )

    if os.path.isdir(source):
        vtk_files = _collect_vtk_files(source)
        if time == "last":
            selected_files = vtk_files[-1:]
        elif time == "index":
            selected_files = [vtk_files[time_index]]
        else:
            selected_files = vtk_files[-n_last:]
    else:
        if not os.path.isfile(source):
            raise FileNotFoundError(f"VTK file not found: {source}")
        selected_files = [source]

    mesh0 = pv.read(selected_files[0])
    coords = np.asarray(mesh0.points)

    resolved_variables = _resolve_openfoam_variables(
        variables, list(mesh0.point_data.keys())
    )
    field_names = sorted({field for _, field, _ in resolved_variables})

    # Average the requested fields over the selected time steps.
    field_data = {
        field: np.asarray(mesh0.point_data[field], dtype=float).copy()
        for field in field_names
    }
    for vtk_file in selected_files[1:]:
        mesh = pv.read(vtk_file)
        for field in field_names:
            field_data[field] += np.asarray(mesh.point_data[field], dtype=float)
    for field in field_names:
        field_data[field] /= len(selected_files)

    tree = spatial.cKDTree(coords)
    k_use = 1 if method == "nearest" else min(k, len(coords))

    records = []

    for i in range(x_pts.size):
        target = np.array([x_pts[i], y_pts[i], z_pts[i]])

        _, idx = tree.query(target, k=k_use)
        idx = np.atleast_1d(idx)
        weights = _idw_weights(coords[idx], target) if k_use > 1 else np.array([1.0])

        record = {"point": i, "x": x_pts[i], "y": y_pts[i], "z": z_pts[i]}

        for name, field, component in resolved_variables:
            values = field_data[field][idx]

            if values.ndim == 1:
                record[name] = float(weights @ values)
            elif component is not None:
                record[name] = float(weights @ values[:, component])
            else:
                # Vector field requested without component: magnitude.
                record[name] = float(
                    np.linalg.norm(weights @ values)
                )

        records.append(record)

    return pd.DataFrame(records)
